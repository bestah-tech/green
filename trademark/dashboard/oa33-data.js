// 조항표제 조립 [SPEC §2-2] — 항상 오름차순, 마지막만 '및'
export function assembleGroundsTitle(grounds) {
  const sorted = [...new Set(grounds)].sort((a, b) => a - b);
  if (sorted.length === 0) return "";
  if (sorted.length === 1) return `제${sorted[0]}호`;
  if (sorted.length === 2) return `제${sorted[0]}호 및 제${sorted[1]}호`;
  const heads = sorted.slice(0, -1).map((g) => `제${g}호`).join(", ");
  return `${heads} 및 제${sorted[sorted.length - 1]}호`;
}

// 규칙 엔진 [SPEC §2-2] — LLM 판단의 교차검사용
export function ruleGrounds(components, options = {}) {
  const roles = new Set((components || []).map((c) => c.role));
  let grounds = new Set([3, 7]);
  if (roles.has("지명")) grounds.add(4);
  if (roles.has("성씨")) grounds.add(5);
  if (roles.has("간단흔한")) grounds.add(6);
  if (options.propertyDisplayDoubtful && roles.has("다수공존")) grounds = new Set([7]);
  return [...grounds].sort((a, b) => a - b);
}

